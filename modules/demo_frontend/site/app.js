"use strict";

// ── Config ──────────────────────────────────────────────────────────────────
// config.js is generated by Terraform and defines window.APP_CONFIG.
const API_URL = ((window.APP_CONFIG && window.APP_CONFIG.apiUrl) || "").replace(/\/+$/, "");
const THRESHOLD = 4;
const POLL_INTERVAL_MS = 4000;
const POLL_TIMEOUT_MS = 6 * 60 * 1000;

const ANALYSTS = [
  ["Sarah", "Network"], ["Marc", "Phishing"], ["David", "Forensics"], ["Lisa", "Malware"], ["Chen", "Cloud"],
];
const THREATS = ["Ransomware", "Data Exfiltration", "Phishing Campaign", "SQL Injection", "DDoS Attack"];

// The README / SETUP example (USD). Smaller sizes use its top-left corner.
const EXAMPLE = [
  [72000, 95000, 98000, 75000, 37000],
  [112000, 31000, 67000, 99000, 49000],
  [56000, 65000, 111000, 106000, 34000],
  [61000, 120000, 28000, 77000, 115000],
  [107000, 101000, 10000, 81000, 19000],
];

let currentN = 4;
let pollTimer = null;
let clockTimer = null;

// ── Helpers ─────────────────────────────────────────────────────────────────
const $ = (id) => document.getElementById(id);

// Every value that comes from the API or user input goes through escapeHtml
// before it touches innerHTML. Dynamic sizes/colours are set via element.style
// (CSSOM), which the Content-Security-Policy allows, never via style="" markup.
function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// Display names: "Sarah (Network)", and the first n analysts / threats for size n.
const analystLabel = (i) => `${ANALYSTS[i][0]} (${ANALYSTS[i][1]})`;
const analystNames = (n) => ANALYSTS.slice(0, n).map((_, i) => analystLabel(i));
const threatNames = (n) => THREATS.slice(0, n);

// n! = number of possible assignments for n analysts.
function factorial(n) {
  let r = 1;
  for (let i = 2; i <= n; i++) r *= i;
  return r;
}

// 209000 -> "$209,000" (or an em dash if the value is missing).
function formatUSD(val) {
  const num = Number(val);
  return Number.isFinite(num) ? "$" + num.toLocaleString("en-US") : "—";
}

// 0.403 -> "40.3%".
function formatPct(val, digits = 1) {
  const num = Number(val);
  return Number.isFinite(num) ? (num * 100).toFixed(digits) + "%" : "—";
}

// Random cost between $10,000 and $120,000, and a shortcut to the input cell (i, j).
const randCost = () => Math.round(Math.random() * 110 + 10) * 1000;
const cell = (i, j) => $(`c${i}_${j}`);

// Small check-mark icon shown next to "Proven optimal".
const ICON_CHECK = '<svg viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M20 6 9 17l-5-5"/></svg>';

// ── Layout ──────────────────────────────────────────────────────────────────
// Switch team size: update the selector, rebuild the table, reset the result.
function setSize(n) {
  currentN = n;
  document.querySelectorAll("#size-select button").forEach((b) => {
    b.setAttribute("aria-checked", String(Number(b.dataset.n) === n));
  });
  buildTable(n);
  updateMode(n);
  resetResult();
}

// Classical (green) vs quantum (purple) badge, button and info line for size n.
function updateMode(n) {
  const quantum = n > THRESHOLD;
  const fact = factorial(n).toLocaleString("en-US");
  const sep = '<span class="info-sep">·</span>';

  $("mode-badge").className = `mode-badge ${quantum ? "quantum" : "classical"}`;
  $("mode-label").textContent = quantum ? "Quantum · QAOA on Braket" : "Classical · exact";
  $("btn-submit").className = `btn btn-primary ${quantum ? "quantum" : "classical"}`;
  $("info-bar").className = `info-bar${quantum ? " quantum-mode" : ""}`;
  $("info-bar").innerHTML = quantum
    ? `<span>${n * n} qubits</span> ${sep} <span>${fact}</span> possible assignments ${sep} QAOA on Amazon Braket SV1 ${sep} verified classically ${sep} ~45 s`
    : `<span>${fact}</span> possible assignments ${sep} every one checked ${sep} guaranteed optimum ${sep} ~2 s`;
}

// Build the n x n table of cost inputs with analyst rows and threat columns.
function buildTable(n) {
  let html = '<thead><tr><th class="corner"></th>';
  threatNames(n).forEach((t) => { html += `<th class="col-header" scope="col">${escapeHtml(t)}</th>`; });
  html += "</tr></thead><tbody>";
  for (let i = 0; i < n; i++) {
    const [name, role] = ANALYSTS[i];
    html += `<tr><th class="row-header" scope="row">${escapeHtml(name)}<span class="row-role">${escapeHtml(role)}</span></th>`;
    threatNames(n).forEach((t, j) => {
      html += `<td><input type="text" inputmode="numeric" id="c${i}_${j}" placeholder="—" autocomplete="off"
        aria-label="${escapeHtml(name)} on ${escapeHtml(t)}, USD"/></td>`;
    });
    html += "</tr>";
  }
  $("cost-table").innerHTML = html + "</tbody>";
}

// Heat-map: shade every filled cell from green (cheapest) to red (most expensive).
function paintHeatmap() {
  const values = [];
  for (let i = 0; i < currentN; i++) {
    for (let j = 0; j < currentN; j++) {
      const v = parseInt(cell(i, j).value, 10);
      if (!Number.isNaN(v)) values.push(v);
    }
  }
  const min = Math.min(...values);
  const max = Math.max(...values);
  for (let i = 0; i < currentN; i++) {
    for (let j = 0; j < currentN; j++) {
      const el = cell(i, j);
      const v = parseInt(el.value, 10);
      if (Number.isNaN(v) || values.length < 2 || max === min) {
        el.style.backgroundColor = "";
        continue;
      }
      const t = (v - min) / (max - min);        // 0 = cheapest, 1 = most expensive
      const hue = 150 - 150 * t;                // green -> red
      el.style.backgroundColor = `hsla(${hue.toFixed(0)}, 75%, 45%, ${(0.12 + 0.16 * t).toFixed(2)})`;
    }
  }
}

// Remove the gold "optimal" outline from every cell.
function clearHighlights() {
  document.querySelectorAll("#cost-table input.is-optimal").forEach((el) => el.classList.remove("is-optimal"));
}

// Keep only digits (max 6) while typing, then refresh the heat-map.
function onCellInput(event) {
  const el = event.target;
  if (el.tagName !== "INPUT") return;
  el.value = el.value.replace(/\D/g, "").slice(0, 6);
  clearHighlights();
  paintHeatmap();
}

// Fill every cell with getValue(i, j), then refresh colours and clear old results.
function fill(getValue) {
  for (let i = 0; i < currentN; i++) {
    for (let j = 0; j < currentN; j++) cell(i, j).value = getValue(i, j);
  }
  clearHighlights();
  paintHeatmap();
  resetResult();
}

// Button actions: random values, the README example, or empty cells.
const generateValues = () => fill(() => randCost());
const loadExample = () => fill((i, j) => EXAMPLE[i][j]);
const clearTable = () => fill(() => "");

// Read the table into a matrix of numbers, or null if any cell is empty/invalid.
function readMatrix() {
  const matrix = [];
  for (let i = 0; i < currentN; i++) {
    const row = [];
    for (let j = 0; j < currentN; j++) {
      const v = parseInt(cell(i, j).value, 10);
      if (Number.isNaN(v) || v < 0) return null;
      row.push(v);
    }
    matrix.push(row);
  }
  return matrix;
}

// ── API ─────────────────────────────────────────────────────────────────────
async function submitJob() {
  const n = currentN;
  const matrix = readMatrix();
  if (!matrix) {
    showError("Fill every cell first, or use “Load README example” / “Random values”.");
    return;
  }
  const payload = { analysts: analystNames(n), alerts: threatNames(n), cost_matrix: matrix };

  setSubmitting(true);
  resetResult();
  try {
    const resp = await fetch(`${API_URL}/optimize`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    const data = await resp.json().catch(() => ({}));

    if (resp.status === 202 && data.status === "PENDING") {
      showQuantumStatus(data);
      startPolling(data.job_id);
    } else if (resp.ok) {
      setSubmitting(false);
      showResult(data);
    } else {
      setSubmitting(false);
      showError(data.error || (resp.status === 429
        ? "Too many requests. Please wait a moment and try again."
        : `Unexpected error from the optimizer (HTTP ${resp.status}).`));
    }
  } catch (e) {
    setSubmitting(false);
    showError(`Network error: ${e.message}`);
  }
}

// Ask GET /jobs/{id} every 4 s until the quantum job completes, fails or times out.
function startPolling(jobId) {
  stopPolling();
  const started = Date.now();

  const poll = async () => {
    if (Date.now() - started > POLL_TIMEOUT_MS) {
      finishQuantum();
      showError(`The quantum job is taking longer than expected. Job ID: ${jobId}`);
      return;
    }
    try {
      const resp = await fetch(`${API_URL}/jobs/${encodeURIComponent(jobId)}`);
      const data = await resp.json().catch(() => ({}));
      if (data.status === "COMPLETE") {
        setProgress("done");
        finishQuantum();
        showResult(data);
        return;
      }
      if (data.status === "FAILED" || resp.status === 404 || resp.status === 400) {
        finishQuantum();
        showError(data.error || "The quantum job failed.");
        return;
      }
      setProgress(/running/i.test(data.message || "") ? "running" : "submitted");
    } catch (_) {
      // transient network error: keep polling until the timeout
    }
    pollTimer = setTimeout(poll, POLL_INTERVAL_MS);
  };
  pollTimer = setTimeout(poll, POLL_INTERVAL_MS);
}

// Stop the polling timer and the seconds counter.
function stopPolling() {
  clearTimeout(pollTimer);
  clearInterval(clockTimer);
  pollTimer = null;
  clockTimer = null;
}

// Quantum job is over (either way): stop timers, hide progress, re-enable buttons.
function finishQuantum() {
  stopPolling();
  hideQuantumStatus();
  setSubmitting(false);
}

// ── Quantum progress ────────────────────────────────────────────────────────
// The four steps of the quantum progress tracker, in order.
const STEP_ORDER = ["queued", "submitted", "running", "verify"];

// Mark tracker steps before `stage` as done and `stage` itself as active.
function setProgress(stage) {
  // "running" also marks verification as active once the task has run a while
  const reached = stage === "done" ? STEP_ORDER.length : STEP_ORDER.indexOf(stage);
  document.querySelectorAll("#qs-steps li").forEach((li, idx) => {
    li.classList.toggle("done", idx < reached);
    li.classList.toggle("active", idx === reached);
  });
}

// Show the quantum progress card and start the elapsed-seconds counter.
function showQuantumStatus(data) {
  $("quantum-status").className = "card quantum-card show";
  $("qs-info").textContent =
    `Job ${data.job_id} · ${data.qubits} qubits · ${Number(data.shots).toLocaleString("en-US")} shots`;
  setProgress("submitted");
  const started = Date.now();
  $("qs-timer").textContent = "0 s";
  clockTimer = setInterval(() => {
    $("qs-timer").textContent = `${Math.round((Date.now() - started) / 1000)} s`;
  }, 1000);
}

// Hide the quantum progress card.
function hideQuantumStatus() {
  $("quantum-status").className = "card quantum-card";
}

// ── Rendering ───────────────────────────────────────────────────────────────
function renderQaoa(q) {
  if (!q) return "";
  let verdict;
  if (q.qaoa_cost === null || q.qaoa_cost === undefined) {
    verdict = "None of the sampled bitstrings encoded a valid assignment.";
  } else if (q.qaoa_found_optimum) {
    verdict = "The quantum circuit’s best valid sample <strong>matched the proven optimum</strong>.";
  } else {
    verdict = `The quantum circuit’s best valid sample was <strong>${escapeHtml(q.qaoa_gap_pct)}%</strong> above the optimum.`;
  }
  // Like-for-like comparison: among valid assignments, how often QAOA hit the
  // optimum vs. how often a uniformly random valid assignment would.
  const optimalAmongValid = Number(q.feasible_fraction) > 0
    ? Number(q.optimal_fraction) / Number(q.feasible_fraction) : 0;
  const lift = Number(q.random_baseline_optimal_fraction) > 0
    ? optimalAmongValid / Number(q.random_baseline_optimal_fraction) : 0;
  const metric = (label, value) =>
    `<div class="qaoa-metric"><span class="label">${label}</span><span class="value">${value}</span></div>`;
  const prob = (label, cls, value, digits) => `
    <div class="prob-row">
      <span class="prob-label">${label}</span>
      <div class="prob-track"><div class="prob-fill ${cls}" data-pct="${Number(value) || 0}"></div></div>
      <span class="prob-value">${formatPct(value, digits)}</span>
    </div>`;

  return `
    <div class="qaoa-panel">
      <div class="qaoa-head">
        <h3>⚛ Quantum circuit performance</h3>
        <span class="qaoa-spec">QAOA · ${escapeHtml(q.qubits)} qubits · p = ${escapeHtml(q.layers)} · Amazon Braket SV1</span>
      </div>
      <div class="qaoa-grid">
        ${metric("Shots", Number(q.shots).toLocaleString("en-US"))}
        ${metric("Valid samples", formatPct(q.feasible_fraction))}
        ${metric("Optimal samples", formatPct(q.optimal_fraction))}
        ${metric("Best sampled cost", formatUSD(q.qaoa_cost))}
      </div>
      ${prob("Shots that are a valid assignment", "valid", q.feasible_fraction, 1)}
      ${prob("Valid shots that are optimal (QAOA)", "optimal", optimalAmongValid, 1)}
      ${prob("Random valid assignment is optimal", "random", q.random_baseline_optimal_fraction, 1)}
      <p class="qaoa-note">${verdict} Among its valid samples, the circuit chose the optimal assignment <strong>${lift.toFixed(0)}× more often</strong> than random selection would. The recommendation above is the exact optimum, confirmed by checking all ${Number(factorial(currentN)).toLocaleString("en-US")} assignments classically.</p>
    </div>`;
}

// Outline in gold the table cells chosen by the optimal assignment.
function highlightAssignment(pairs) {
  const analysts = analystNames(currentN);
  const threats = threatNames(currentN);
  pairs.forEach((p) => {
    const i = analysts.indexOf(p.analyst);
    const j = threats.indexOf(p.alert);
    if (i >= 0 && j >= 0) cell(i, j).classList.add("is-optimal");
  });
}

// Render the full result card: KPIs, comparison bars, assignment, QAOA panel, summary.
function showResult(data) {
  const isQuantum = data.method === "QUANTUM";
  const cls = isQuantum ? "quantum" : "classical";
  const pairs = data.assignment || [];
  const total = Number(data.total_cost);
  const greedy = Number(data.greedy_cost);
  const savings = Number(data.savings);
  const savingPct = greedy > 0 ? Math.round((savings / greedy) * 100) : 0;

  const pairsHtml = pairs.map((p) => `
    <div class="pair-card ${cls}">
      <div class="pair-names">${escapeHtml(p.analyst)}<span class="pair-arrow">→</span><span class="pair-alert">${escapeHtml(p.alert)}</span></div>
      <div class="pair-cost">${formatUSD(p.cost)} breach impact</div>
    </div>`).join("");

  const source = data.narrative_source === "bedrock"
    ? "Generated by Claude on Amazon Bedrock from the figures above"
    : "Template summary (Bedrock unavailable)";

  const panel = $("result-panel");
  panel.className = "card result-card show";
  panel.innerHTML = `
    <div class="result-top">
      <span class="result-kicker ${cls}">${isQuantum ? "⚛ Hybrid: QAOA + classical verification" : "∑ Exact classical optimization"}</span>
      <span class="result-verified">${ICON_CHECK} Proven optimal · ${Number(data.combinations_evaluated).toLocaleString("en-US")} assignments checked</span>
    </div>

    <div class="kpis">
      <div class="kpi primary"><span class="kpi-label">Total exposure</span><span class="kpi-value">${formatUSD(total)}</span><span class="kpi-note">optimal assignment</span></div>
      <div class="kpi"><span class="kpi-label">Intuitive (greedy)</span><span class="kpi-value">${formatUSD(greedy)}</span><span class="kpi-note">each analyst takes their cheapest open threat</span></div>
      <div class="kpi saving"><span class="kpi-label">Saved</span><span class="kpi-value">${formatUSD(savings)}</span><span class="kpi-note">${savingPct}% less than greedy</span></div>
    </div>

    <div class="compare">
      <div class="compare-row"><span class="compare-label">Optimal</span><div class="compare-track"><div class="compare-fill optimal" data-pct="${greedy > 0 ? total / greedy : 1}"></div></div><span class="compare-value">${formatUSD(total)}</span></div>
      <div class="compare-row"><span class="compare-label">Greedy</span><div class="compare-track"><div class="compare-fill greedy" data-pct="1"></div></div><span class="compare-value">${formatUSD(greedy)}</span></div>
    </div>

    <h3 class="subhead">Recommended assignment</h3>
    <div class="result-grid">${pairsHtml}</div>

    ${isQuantum ? renderQaoa(data.qaoa) : ""}

    <div class="narrative">
      <div class="narrative-title">✦ Board summary</div>
      <p>${escapeHtml(data.narrative)}</p>
      <span class="narrative-source">${source}</span>
    </div>`;

  highlightAssignment(pairs);

  // Animate bars after layout (CSSOM width, allowed by the CSP)
  requestAnimationFrame(() => {
    panel.querySelectorAll("[data-pct]").forEach((el) => {
      const pct = Math.max(0, Math.min(1, Number(el.dataset.pct) || 0));
      el.style.width = `${(pct * 100).toFixed(1)}%`;
    });
  });
  panel.scrollIntoView({ behavior: "smooth", block: "start" });
}

// Show an error message in the result card.
function showError(msg) {
  const panel = $("result-panel");
  panel.className = "card result-card show";
  panel.innerHTML = `<div class="error-box">⚠ <span>${escapeHtml(msg)}</span></div>`;
}

// Disable/enable the controls while a request is running.
function setSubmitting(on) {
  ["btn-submit", "btn-generate", "btn-example", "btn-clear"].forEach((id) => { $(id).disabled = on; });
  document.querySelectorAll("#size-select button").forEach((b) => { b.disabled = on; });
  $("btn-submit").innerHTML = on
    ? '<span class="spinner inline"></span> Optimizing…'
    : "Find optimal assignment";
}

// Clear any previous result, highlights and running job.
function resetResult() {
  stopPolling();
  hideQuantumStatus();
  clearHighlights();
  const p = $("result-panel");
  p.className = "card result-card";
  p.innerHTML = "";
}

